-- HealthWise USA initial Supabase schema
-- Safe to apply to an empty project. All public tables have RLS enabled.
create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  name text not null default '',
  role text not null default 'user' check (role in ('user','editor','admin')),
  status text not null default 'active' check (status in ('active','suspended','deleted')),
  avatar_url text,
  dietary_prefs text[] not null default '{}',
  measurement_unit text not null default 'us' check (measurement_unit in ('us','metric')),
  newsletter_opt_in boolean not null default false,
  created_at timestamptz not null default now(),
  last_login_at timestamptz
);

